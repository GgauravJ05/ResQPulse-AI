"""Merge public + synthetic data into the final splits and the Flan-T5 files.

Reads  data/processed/public_{train,val,test}.csv   (scripts/build_public.py)
       data/processed/synthetic_clean.csv           (scripts/validate_synthetic.py)
Writes data/processed/
    train.csv, val.csv          public + synthetic (synthetic train rows repeated --synth-repeat times)
    test_synth.csv              synthetic only: call-style reports with all labels
    test_public.csv             real tweets only: HumAID test + held-out CrisisLex crises
    train_flan.csv, val_flan.csv, test_flan.csv   id, input, target  (synthetic rows only)
    reports/data_card.md        counts per type / source / split

Run from the repo root:  .venv/bin/python scripts/make_splits.py
"""
import argparse
import csv
import json
import sys
from pathlib import Path

import pandas as pd
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity
from sklearn.model_selection import train_test_split

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src.data.flan import format_input, format_target  # noqa: E402

SEED = 42
PROC = Path("data/processed")
LEAK_THRESHOLD = 0.85   # val/test synthetic rows this similar to a train row are dropped


def write(df: pd.DataFrame, name: str) -> None:
    df.to_csv(PROC / name, index=False, quoting=csv.QUOTE_NONNUMERIC)
    print(f"wrote {name}: {len(df):,} rows")


def flan_frame(df: pd.DataFrame) -> pd.DataFrame:
    targets = [format_target(json.loads(f)) for f in df["fields_json"]]
    return pd.DataFrame({"id": df["id"], "input": [format_input(t) for t in df["text"]], "target": targets})


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--public-cap", type=int, default=1200, help="max public training rows per incident type")
    ap.add_argument("--synth-repeat", type=int, default=4, help="repeat synthetic train rows this many times")
    args = ap.parse_args()

    syn = pd.read_csv(PROC / "synthetic_clean.csv", dtype=str, keep_default_na=False)
    pub = {s: pd.read_csv(PROC / f"public_{s}.csv", dtype=str, keep_default_na=False)
           for s in ["train", "val", "test"]}

    # 1. Stratified 70/15/15 split of the synthetic reports
    tr, rest = train_test_split(syn, test_size=0.30, stratify=syn["incident_type"], random_state=SEED)
    va, te = train_test_split(rest, test_size=0.50, stratify=rest["incident_type"], random_state=SEED)
    tr, va, te = (d.assign(split=s) for d, s in [(tr, "train"), (va, "val"), (te, "test")])

    # 2. Drop val/test synthetic rows that are near-copies of a train row
    vec = TfidfVectorizer(ngram_range=(1, 2), sublinear_tf=True).fit(syn["text"])
    tr_vec = vec.transform(tr["text"])
    for name, part in [("val", va), ("test", te)]:
        sim = cosine_similarity(vec.transform(part["text"]), tr_vec).max(axis=1)
        keep = sim <= LEAK_THRESHOLD
        print(f"synthetic {name}: dropped {int((~keep).sum())} rows too similar to train")
        part.drop(part.index[~keep], inplace=True)

    # 3. Cap public training rows per class so synthetic call-style reports are not drowned out
    p_tr = pd.concat([g.sample(min(len(g), args.public_cap), random_state=SEED)
                      for _, g in pub["train"].groupby("incident_type")], ignore_index=True)

    train = pd.concat([p_tr] + [tr] * args.synth_repeat, ignore_index=True)
    val = pd.concat([pub["val"], va], ignore_index=True)
    train = train.sample(frac=1, random_state=SEED).reset_index(drop=True)
    val = val.sample(frac=1, random_state=SEED).reset_index(drop=True)

    PROC.mkdir(parents=True, exist_ok=True)
    write(train, "train.csv")
    write(val, "val.csv")
    write(te.reset_index(drop=True), "test_synth.csv")
    write(pub["test"], "test_public.csv")
    write(flan_frame(tr), "train_flan.csv")
    write(flan_frame(va), "val_flan.csv")
    write(flan_frame(te), "test_flan.csv")

    # 4. Data card
    lines = ["# Data card (generated by scripts/make_splits.py)", "",
             f"Public training rows are capped at {args.public_cap} per incident type; synthetic training rows are "
             f"repeated {args.synth_repeat}x in `train.csv` (the unrepeated rows are in `train_flan.csv`).", ""]
    for name, df in [("train", train), ("val", val), ("test_synth", te), ("test_public", pub["test"])]:
        lines += [f"## {name} ({len(df):,} rows)", "", "By incident type:", "",
                  df["incident_type"].value_counts().to_markdown(), "", "By data source:", "",
                  df["data_source"].value_counts().to_markdown(), ""]
    Path("reports").mkdir(exist_ok=True)
    Path("reports/data_card.md").write_text("\n".join(lines), encoding="utf-8")
    print("wrote reports/data_card.md")

    print("\ntrain.csv rows per incident_type x data_source:")
    print(pd.crosstab(train["incident_type"], train["data_source"]))


if __name__ == "__main__":
    main()
